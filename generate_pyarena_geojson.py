# Assemblage selon la norme GeoJSON RFC 7946 (FeatureCollection)
features = []
for a in arenas_data:
    feature = {
        "type": "Feature",
        "geometry": {
            "type": "Point",
            "coordinates": [a["lon"], a["lat"]],  # [Longitude, Latitude]
        },
        "properties": {
            "id": a["id"],
            "name": a["name"],
            "city": a["city"],
            "level": a["level"],
            "type": a["type"],
            "champion_name": a["champion"],
            "pokemon_id": a["pokemon_id"],
            "pokemon_name": a["pokemon_name"],
        },
    }
    features.append(feature)

geojson_payload = {
    "type": "FeatureCollection",
    "features": features,
}

output_path = Path("data_pyarena/arenes_occitanie.geojson")
output_path.parent.mkdir(parents=True, exist_ok=True)

with open(output_path, "w", encoding="utf-8") as f:
    json.dump(geojson_payload, f, ensure_ascii=False, indent=2)

print(f"GeoJSON des 30 arènes généré sous : {output_path.resolve()}")
